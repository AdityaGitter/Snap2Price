import React, { useState, useEffect } from 'react';
import { useSearchParams, Link } from 'react-router-dom';
import {
  Layers, Sparkles, Award, CheckCircle2, ShoppingCart, X,
  Plus, AlertCircle, TrendingUp
} from 'lucide-react';
import { api } from '../services/api';
import { Product, CompareResponse } from '../types';
import { useCart } from '../context/CartContext';
import { useToast } from '../context/ToastContext';

export const ProductComparisonPage: React.FC = () => {
  const [searchParams, setSearchParams] = useSearchParams();
  const { addToCart } = useCart();
  const { success, error } = useToast();

  const [availableProducts, setAvailableProducts] = useState<Product[]>([]);
  const [selectedIds, setSelectedIds] = useState<number[]>([]);
  const [comparisonData, setComparisonData] = useState<CompareResponse | null>(null);
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    const fetchCatalog = async () => {
      try {
        const res = await api.getProducts({ page_size: 48 });
        setAvailableProducts(res.items);

        // Check if IDs provided in URL
        const idsParam = searchParams.get('ids');
        if (idsParam) {
          const parsed = idsParam.split(',').map((id) => parseInt(id, 10)).filter(Boolean);
          if (parsed.length >= 2) {
            setSelectedIds(parsed);
            runComparison(parsed);
            return;
          }
        }

        // Default comparison pair if none provided
        if (res.items.length >= 2) {
          const defaultPair = [res.items[0].id, res.items[1].id];
          setSelectedIds(defaultPair);
          runComparison(defaultPair);
        }
      } catch (err) {
        console.error('Failed to load products for comparison', err);
      }
    };
    fetchCatalog();
  }, []);

  const runComparison = async (ids: number[]) => {
    if (ids.length < 2) {
      setComparisonData(null);
      return;
    }
    setLoading(true);
    try {
      const data = await api.compareProducts(ids);
      setComparisonData(data);
      setSearchParams({ ids: ids.join(',') });
    } catch (err) {
      error('Failed to run AI comparison');
    } finally {
      setLoading(false);
    }
  };

  const handleAddProduct = (id: number) => {
    if (selectedIds.includes(id)) return;
    if (selectedIds.length >= 4) {
      error('You can compare a maximum of 4 products.');
      return;
    }
    const updated = [...selectedIds, id];
    setSelectedIds(updated);
    runComparison(updated);
  };

  const handleRemoveProduct = (id: number) => {
    const updated = selectedIds.filter((pid) => pid !== id);
    setSelectedIds(updated);
    if (updated.length >= 2) {
      runComparison(updated);
    } else {
      setComparisonData(null);
      setSearchParams({});
    }
  };

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-10">
      {/* Header */}
      <div className="text-center max-w-2xl mx-auto space-y-3">
        <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-purple-100 text-purple-700 text-xs font-bold">
          <Layers className="w-3.5 h-3.5" />
          <span>Side-by-Side Product Comparison</span>
        </div>
        <h1 className="text-3xl sm:text-4xl font-extrabold text-slate-900 tracking-tight">
          AI Product Comparison Matrix
        </h1>
        <p className="text-sm text-slate-600 leading-relaxed">
          Compare hardware specs, pricing, review ratings, and get an objective buying verdict generated by Google Gemini AI.
        </p>
      </div>

      {/* Select Products Bar */}
      <div className="bg-white p-6 rounded-3xl border border-slate-200 shadow-sm space-y-4">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <h3 className="font-bold text-sm text-slate-900">Comparing {selectedIds.length} Products (Min 2, Max 4)</h3>
            <p className="text-xs text-slate-500">Add or remove items to customize the comparative matrix</p>
          </div>

          <div className="flex items-center gap-2">
            <select
              onChange={(e) => {
                if (e.target.value) handleAddProduct(parseInt(e.target.value, 10));
              }}
              defaultValue=""
              className="text-xs p-2.5 rounded-xl border border-slate-200 bg-white font-medium text-slate-700 outline-none cursor-pointer"
            >
              <option value="" disabled>+ Add Product to Compare</option>
              {availableProducts
                .filter((p) => !selectedIds.includes(p.id))
                .map((p) => (
                  <option key={p.id} value={p.id}>
                    {p.name} (₹{p.price.toLocaleString('en-IN')})
                  </option>
                ))}
            </select>
          </div>
        </div>

        {/* Selected Products Chips */}
        <div className="flex flex-wrap gap-2 pt-2">
          {selectedIds.map((id) => {
            const prod = availableProducts.find((p) => p.id === id);
            if (!prod) return null;
            return (
              <span
                key={id}
                className="inline-flex items-center gap-2 bg-purple-50 border border-purple-200 text-purple-800 px-3 py-1.5 rounded-full text-xs font-semibold"
              >
                <span className="truncate max-w-xs">{prod.name}</span>
                <button
                  type="button"
                  onClick={() => handleRemoveProduct(id)}
                  className="hover:text-rose-600"
                >
                  <X className="w-3.5 h-3.5" />
                </button>
              </span>
            );
          })}
        </div>
      </div>

      {/* AI Comparison Verdict Section */}
      {comparisonData && (
        <div className="bg-gradient-to-r from-purple-50 via-indigo-50 to-blue-50 border border-purple-200 rounded-3xl p-6 sm:p-8 shadow-sm space-y-6">
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2.5">
              <div className="w-8 h-8 rounded-xl bg-purple-600 text-white flex items-center justify-center">
                <Sparkles className="w-4 h-4" />
              </div>
              <h3 className="font-extrabold text-base text-slate-900">Google Gemini AI Comparative Verdict</h3>
            </div>
            <span className="text-[10px] uppercase font-bold tracking-wider px-2.5 py-0.5 rounded-full bg-purple-600 text-white">
              AI Decision Engine
            </span>
          </div>

          <p className="text-sm text-slate-700 leading-relaxed font-medium bg-white/70 p-4 rounded-2xl border border-purple-100">
            "{comparisonData.ai_comparison_verdict}"
          </p>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {comparisonData.best_value_winner && (
              <div className="bg-white p-4 rounded-2xl border border-emerald-200 shadow-xs flex items-center gap-3">
                <div className="w-10 h-10 rounded-xl bg-emerald-100 text-emerald-700 flex items-center justify-center flex-shrink-0">
                  <Award className="w-5 h-5" />
                </div>
                <div>
                  <span className="text-[10px] font-bold uppercase tracking-wider text-emerald-600 block">
                    Best Value Winner
                  </span>
                  <span className="text-xs sm:text-sm font-extrabold text-slate-900 block truncate">
                    {comparisonData.best_value_winner}
                  </span>
                </div>
              </div>
            )}

            {comparisonData.best_performance_winner && (
              <div className="bg-white p-4 rounded-2xl border border-indigo-200 shadow-xs flex items-center gap-3">
                <div className="w-10 h-10 rounded-xl bg-indigo-100 text-indigo-700 flex items-center justify-center flex-shrink-0">
                  <TrendingUp className="w-5 h-5" />
                </div>
                <div>
                  <span className="text-[10px] font-bold uppercase tracking-wider text-indigo-600 block">
                    Best Performance Winner
                  </span>
                  <span className="text-xs sm:text-sm font-extrabold text-slate-900 block truncate">
                    {comparisonData.best_performance_winner}
                  </span>
                </div>
              </div>
            )}
          </div>
        </div>
      )}

      {/* Comparison Table */}
      {comparisonData ? (
        <div className="bg-white rounded-3xl border border-slate-200 overflow-hidden shadow-sm">
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="border-b border-slate-200 bg-slate-50/70">
                  <th className="p-4 text-xs font-bold text-slate-500 uppercase tracking-wider w-1/4">Feature</th>
                  {comparisonData.products.map((p) => (
                    <th key={p.id} className="p-4 text-center min-w-[220px]">
                      <div className="flex flex-col items-center gap-2">
                        <img
                          src={p.image_url}
                          alt={p.name}
                          className="w-20 h-20 rounded-xl object-cover bg-slate-100"
                        />
                        <Link
                          to={`/products/${p.slug || p.id}`}
                          className="font-bold text-xs text-slate-900 hover:text-purple-600 line-clamp-2 max-w-[180px]"
                        >
                          {p.name}
                        </Link>
                        <span className="text-sm font-extrabold text-slate-900">
                          ₹{p.price.toLocaleString('en-IN')}
                        </span>
                        <button
                          onClick={() => {
                            addToCart(p, 1);
                            success(`Added "${p.name}" to cart!`);
                          }}
                          className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-purple-600 hover:bg-purple-700 text-white text-[11px] font-bold transition shadow-xs"
                        >
                          <ShoppingCart className="w-3 h-3" />
                          <span>Add to Cart</span>
                        </button>
                      </div>
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 text-xs">
                {comparisonData.comparison_matrix.map((row, idx) => (
                  <tr key={idx} className={idx % 2 === 0 ? 'bg-white' : 'bg-slate-50/40'}>
                    <td className="p-4 font-bold text-slate-700">{row.feature}</td>
                    {comparisonData.products.map((p) => (
                      <td key={p.id} className="p-4 text-center text-slate-600 font-medium">
                        {row[p.id.toString()] || '-'}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      ) : selectedIds.length < 2 ? (
        <div className="bg-white rounded-3xl border border-slate-200 p-12 text-center space-y-3">
          <AlertCircle className="w-10 h-10 text-amber-500 mx-auto" />
          <h3 className="text-base font-bold text-slate-800">Select at least 2 products</h3>
          <p className="text-xs text-slate-500">Pick two or more products from the dropdown above to generate the comparison matrix.</p>
        </div>
      ) : null}
    </div>
  );
};
